package list.OperacoesBasicas;

public class Tarefa {
    // vai ter um atributo descrição
    private String descricao;

    public Tarefa(String descricao) {
        this.descricao = descricao;
    }

    public String getDescricao() {
        return descricao;
    }

    @Override
    public String toString() {
        return descricao;
    }
}
